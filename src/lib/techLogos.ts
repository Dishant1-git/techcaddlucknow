// Light brand colours (JavaScript yellow, etc.) need a dark badge to stay visible.
export function isLight(hex: string) {
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16));
  return 0.299 * r + 0.587 * g + 0.114 * b > 170;
}
